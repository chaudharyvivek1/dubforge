#!/usr/bin/env python3
"""Generate the reference docs from the code, so they cannot drift.

Hand-written reference tables rot: a setting gains a field, a tool gains a parameter, and
the doc keeps describing the previous release. This script reads the actual sources —
`Settings` and its `NUMERIC_RANGES`, the live MCP tool list and its JSON schemas, and the
argparse tree — and writes `docs/configuration.md`, `docs/mcp-tools.md` and
`docs/cli.md`.

`--check` compares what it would write with what is committed and exits non-zero if they
differ. CI runs that, so a change that is not documented fails the build.

    python scripts/gen_reference.py           # rewrite the docs
    python scripts/gen_reference.py --check   # verify they are current
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from dataclasses import MISSING, fields
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
HEADER = "<!-- Generated by scripts/gen_reference.py — edit the code, not this file. -->\n"


# --------------------------------------------------------------------------- helpers


def _type_name(annotation: Any) -> str:
    text = str(annotation)
    text = text.replace("typing.", "").replace("dubforge.", "")
    return text.replace("NoneType", "null")


def _default(value: Any) -> str:
    if value is MISSING:
        return "—"
    if isinstance(value, dict):
        return "`{}`" if not value else f"`{value}`"
    if isinstance(value, list):
        return "`[]`" if not value else f"`{value}`"
    if isinstance(value, str):
        return f'`"{value}"`' if value else "``"
    return f"`{value}`"


def _fmt_range(low: float, high: float) -> str:
    def one(number: float) -> str:
        return str(int(number)) if float(number).is_integer() else str(number)

    return f"{one(low)} – {one(high)}"


def _cell(text: str, limit: int = 160) -> str:
    """Markdown table cells cannot contain newlines or unescaped pipes."""
    flat = " ".join(str(text).split())
    if len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    return flat.replace("|", "\\|")


# ----------------------------------------------------------------------- configuration


def configuration_doc() -> str:
    from dubforge.config import NUMERIC_RANGES, Settings

    lines = [
        HEADER,
        "# Configuration reference\n",
        "Every setting, where it comes from, and what it accepts. Generated from\n"
        "`Settings` and `NUMERIC_RANGES`, so this table cannot describe a field that no\n"
        "longer exists.\n",
        "## How a value is resolved\n",
        "Later wins:\n",
        "1. the default in `Settings`;\n"
        "2. `DUBFORGE_<NAME>` in the environment (booleans accept `1/true/yes/on` and\n"
        "   `0/false/no/off` only — anything else warns and keeps the default);\n"
        "3. a JSON file passed with `--config` (unknown keys are an error, not a shrug);\n"
        "4. a command-line flag.\n",
        "A settings file is validated on load: invalid JSON, a non-object root, an unknown\n"
        "key, a wrong type, `NaN`/`Infinity` or an out-of-range value is a `ConfigError`\n"
        "naming the file and the key. `dubforge validate-config` checks one without\n"
        "starting any work.\n",
        "## Settings\n",
        "| Setting | Environment | Type | Default | Range |",
        "| --- | --- | --- | --- | --- |",
    ]
    for field in fields(Settings):
        if field.name == "env_warnings":
            continue  # diagnostics, not configuration
        span = NUMERIC_RANGES.get(field.name)
        default = (
            field.default_factory()  # type: ignore[misc]
            if field.default_factory is not MISSING
            else field.default
        )
        lines.append(
            "| `{name}` | `DUBFORGE_{env}` | `{type}` | {default} | {span} |".format(
                name=field.name,
                env=field.name.upper(),
                type=_type_name(field.type),
                default=_default(default),
                span=_fmt_range(*span) if span else "—",
            )
        )

    lines += [
        "\n## Limits\n",
        "The limits are refusals, not warnings. They are checked in `plan()` before the\n"
        "first paid call and again between stages while running, and the error names the\n"
        "setting to change.\n",
        "| Limit | Default | What happens when it is hit |",
        "| --- | --- | --- |",
        "| `max_input_bytes` | 4 GiB | `limit_exceeded` before any provider call |",
        "| `max_input_seconds` | 4 h | `limit_exceeded` before any provider call |",
        "| `max_run_seconds` | 4 h | the run stops at the next stage boundary |",
        "| `max_estimated_usd` | 25.0 | `plan()` reports the breach; the run will not start |",
        "| `max_concurrent_jobs` | 2 | further jobs stay `queued` until a slot frees |",
        "| `max_retries` | 2 | per provider HTTP call; `Retry-After` is honoured |",
        "| `job_retention_days` | 30 | `jobs cleanup` default horizon |",
        "\n## Examples\n",
        "A school lab that must not spend more than ₹500 a term and must not leave the\nmachine:\n",
        "```bash\n"
        "export DUBFORGE_MAX_ESTIMATED_USD=6\n"
        "export DUBFORGE_MAX_CONCURRENT_JOBS=1\n"
        "export DUBFORGE_MAX_INPUT_MINUTES=45   # not a setting: use MAX_INPUT_SECONDS\n"
        "export DUBFORGE_MAX_INPUT_SECONDS=2700\n"
        "dubforge dub lesson.mp4 --to hi --asr faster_whisper --translator ollama --tts edge_tts\n"
        "```\n",
        "A studio that wants the best voice and accepts the bill:\n",
        "```bash\n"
        "export DUBFORGE_MAX_ESTIMATED_USD=250\n"
        "export DUBFORGE_MAX_CONCURRENT_JOBS=4\n"
        "dubforge dub feature.mp4 --to hi --asr deepgram --translator openai --tts elevenlabs \\\n"
        "  --voice-pool <id> --fallback\n"
        "```\n",
        "## Related\n",
        "* [docs/limits](#limits) above, and `src/dubforge/limits.py` for the checks.\n"
        "* [docs/providers.md](providers.md) for the provider names these settings accept.\n"
        "* [docs/security.md](security.md) for what may leave the machine.\n",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------------- MCP


def _schema_rows(schema: dict) -> list[tuple[str, str, str, str]]:
    properties = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, spec in properties.items():
        kind = spec.get("type") or ("enum" if spec.get("enum") else "any")
        if isinstance(kind, list):
            kind = " | ".join(kind)
        default = spec.get("default", None)
        shown = "—" if default is None else f"`{default!r}`"
        if spec.get("enum"):
            shown = ", ".join(f"`{value}`" for value in spec["enum"])
        rows.append(
            (
                f"`{name}`",
                "yes" if name in required else "no",
                _cell(str(kind), 40),
                _cell(shown, 80),
            )
        )
    return rows


def mcp_doc() -> str:
    from dubforge.server import ERROR_CODES, build_server

    server = build_server()
    tools = asyncio.run(server.list_tools())
    tools.sort(key=lambda tool: tool.name)

    lines = [
        HEADER,
        "# MCP tool reference\n",
        f"All {len(tools)} tools, generated from the running server: names, descriptions and\n"
        "input schemas are read from the code, so this page is the schema.\n",
        "## Response envelope\n",
        "Every tool returns JSON in one of two shapes:\n",
        "```json\n"
        '{"ok": true,  "…": "the payload"}\n'
        '{"ok": false, "error": {"code": "invalid_argument", "message": "…", "hint": "…"}}\n'
        "```\n",
        "`code` is stable and machine-readable: "
        + ", ".join(f"`{code}`" for code in ERROR_CODES)
        + ".\n"
        "No message contains a key, and no tool returns a stack trace. A failure is always\n"
        "an envelope, never an exception the transport has to render.\n",
        "## The tools\n",
        "| Tool | What it does |",
        "| --- | --- |",
    ]
    for tool in tools:
        summary = (tool.description or "").split("\n")[0]
        lines.append(f"| [`{tool.name}`](#{tool.name.lower()}) | {_cell(summary, 110)} |")

    for tool in tools:
        lines += [
            f"\n## `{tool.name}`\n",
            (tool.description or "").strip() + "\n",
        ]
        # fastmcp exposes the JSON schema as `.parameters` (pydantic model), not `.inputSchema`
        rows = _schema_rows(getattr(tool, "parameters", None) or {})
        if rows:
            lines += [
                "| Parameter | Required | Type | Default / allowed |",
                "| --- | --- | --- | --- |",
            ]
            lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
            lines.append("")
        else:
            lines += ["No parameters.\n"]

    lines += [
        "\n## Not implemented on purpose\n",
        "* `dubforge_analyze_video` — `probe_media` plus `plan_dub` already answer it; a\n"
        "  duplicate tool is a worse contract than a missing one.\n"
        "* `dubforge_extract_audio`, `dubforge_translate_transcript`,\n"
        "  `dubforge_generate_speech` — stage-level tools need segment-level caching first\n"
        "  (see `docs/assessment.md`), otherwise they re-pay for work the pipeline caches.\n"
        "* No progress notifications and no server-side streaming: the MCP transport here is\n"
        "  request/response, so progress is *polled* with `dubforge_get_job_status` rather\n"
        "  than invented.\n",
        "\n## Related\n",
        "* [docs/cli.md](cli.md) — the same operations from a shell.\n"
        "* [skill/SKILL.md](../skill/SKILL.md) — the workflow an agent should follow.\n"
        "* [docs/release-0.2.0.md](release-0.2.0.md) — what changed in this release.\n",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------------- CLI


def _parser_rows(parser) -> list[tuple[str, str, str]]:
    rows = []
    for action in parser._actions:  # argparse exposes no public iterator
        if action.dest in ("help",) or not action.option_strings:
            continue
        flags = ", ".join(f"`{flag}`" for flag in action.option_strings)
        if action.dest == "json":
            default = "off"
        elif action.default in (None, ""):
            default = "—"
        else:
            default = f"`{action.default!r}`"
        rows.append((flags, _cell(action.help or "", 90), default))
    return rows


def cli_doc() -> str:
    from dubforge.cli import build_parser

    parser = build_parser()
    subparsers = next(
        action for action in parser._actions if isinstance(action, argparse._SubParsersAction)
    )
    names = list(subparsers.choices)
    short_help = {
        action.dest: (action.help or "") for action in getattr(subparsers, "_choices_actions", [])
    }

    lines = [
        HEADER,
        "# CLI reference\n",
        "Generated from the argparse tree. Every command that produces data supports\n"
        "`--json`, and machine output is pure ASCII so a legacy console cannot break it.\n",
        "Exit codes: `0` success, `1` QC failed (the run finished and the dub did not pass),\n"
        "`2` the command could not run.\n",
        "## Commands\n",
        "| Command | Purpose |",
        "| --- | --- |",
    ]
    for name in names:
        sub = subparsers.choices[name]
        summary = sub.description or short_help.get(name, "")
        lines.append(f"| [`dubforge {name}`](#dubforge-{name}) | {_cell(summary, 100)} |")

    for name in names:
        sub = subparsers.choices[name]
        summary = (sub.description or short_help.get(name, "")).strip()
        lines += [f"\n## `dubforge {name}`\n", (summary + "\n") if summary else ""]
        rows = _parser_rows(sub)
        if rows:
            lines += [
                "| Flag | Meaning | Default |",
                "| --- | --- | --- |",
            ]
            lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
            lines.append("")
        positionals = [
            action
            for action in sub._actions
            if not action.option_strings and action.dest not in ("help",)
        ]
        if positionals:
            lines.append(
                "Positional arguments: " + ", ".join(f"`{p.dest}`" for p in positionals) + "\n"
            )

    lines += [
        "\n## Typical sessions\n",
        "One file, synchronously, with a QC gate:\n",
        "```bash\n"
        "dubforge plan lesson.mp4 --to hi            # cost and blockers first\n"
        "dubforge dub lesson.mp4 --to hi --json | jq '.qc.failures'\n"
        "```\n",
        "A term's lessons, in the background, with a ledger:\n",
        "```bash\n"
        "dubforge batch lessons/ --to hi --estimate --workdir ./work\n"
        "dubforge jobs list --status failed --workdir ./work\n"
        "dubforge jobs retry <job-id> --workdir ./work\n"
        "```\n",
        "Diagnosing a machine:\n",
        "```bash\ndubforge doctor && dubforge capabilities && dubforge validate-config\n```\n",
        "\n## Related\n",
        "* [docs/configuration.md](configuration.md) — every setting these flags override.\n"
        "* [docs/mcp-tools.md](mcp-tools.md) — the same operations as agent tools.\n",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------------- main

TARGETS = {
    "configuration.md": configuration_doc,
    "mcp-tools.md": mcp_doc,
    "cli.md": cli_doc,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the reference docs from code.")
    parser.add_argument("--check", action="store_true", help="fail if the docs are stale")
    parser.add_argument("--out", default=str(DOCS), help="output directory (default docs/)")
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    stale: list[str] = []
    for name, build in TARGETS.items():
        target = out_dir / name
        content = build()
        if args.check:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != content:
                stale.append(
                    str(target.relative_to(ROOT)) if target.is_relative_to(ROOT) else str(target)
                )
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"wrote {target} ({len(content.splitlines())} lines)")

    if args.check:
        if stale:
            print(
                "reference docs are stale — run `python scripts/gen_reference.py`:\n  "
                + "\n  ".join(stale),
                file=sys.stderr,
            )
            return 1
        print(f"reference docs are current ({len(TARGETS)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
